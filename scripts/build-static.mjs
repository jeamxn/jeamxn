import { cp, mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { portfolio } from "../packages/core/dist/index.js";
import { generateResumePdf } from "../packages/resume-pdf/dist/index.js";
import { basePath, siteUrl } from "./static-config.mjs";

const root = path.resolve(import.meta.dirname, "..");
const output = path.join(root, "apps/web/build/client");
const base = basePath(),
  site = siteUrl();
const routes = [
  "/",
  "/about",
  "/work",
  "/resume",
  ...portfolio.projects.map((p) => `/work/${p.slug}`),
  ...portfolio.activities.flatMap((a) => (a.slug ? [`/activity/${a.slug}`] : [])),
];
// React Router prerender output may be nested under basename. Publish the site's
// contents, not the hosting prefix: Pages mounts the artifact at that prefix.
if (base !== "/") {
  const nested = path.join(output, base.slice(1));
  try {
    await stat(path.join(nested, "index.html"));
    for (const entry of await readdir(nested))
      await cp(path.join(nested, entry), path.join(output, entry), { recursive: true });
    await rm(nested, { recursive: true });
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
}
for (const route of routes) {
  const file = path.join(output, route, "index.html");
  await stat(file);
}
const pdf = await generateResumePdf();
await writeFile(path.join(output, "resume.pdf"), pdf);
// Dev uses the same generated file. It is ignored in Git and regenerated by CI.
await mkdir(path.join(root, "apps/web/public"), { recursive: true });
await writeFile(path.join(root, "apps/web/public/resume.pdf"), pdf);
const escapeXml = (value) =>
  value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll('"', "&quot;");
const urls = routes.map((route) => `${site}${route === "/" ? "/" : `${route}/`}`);
await writeFile(
  path.join(output, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map((url) => `  <url><loc>${escapeXml(url)}</loc></url>`).join("\n")}\n</urlset>\n`,
);
await writeFile(
  path.join(output, "robots.txt"),
  `User-agent: *\nAllow: /\nSitemap: ${site}/sitemap.xml\n`,
);
await writeFile(path.join(output, ".nojekyll"), "");
// Actual 404 response on Pages; no SPA redirect hack or fake successful route.
await writeFile(
  path.join(output, "404.html"),
  `<!doctype html><html lang="ko"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex"><title>페이지를 찾지 못했어요 | 최재민</title><style>body{font-family:system-ui,sans-serif;background:#f7f7f7;color:#222;max-width:640px;margin:15vh auto;padding:24px;line-height:1.7}a{color:inherit}</style><h1>페이지를 찾지 못했어요</h1><p>주소를 확인하거나 첫 화면에서 다시 살펴보세요</p><a href="${escapeXml(base)}">첫 화면으로</a></html>\n`,
);
// Never publish build-time server stubs, manifests, source maps or local research.
await rm(path.join(output, ".vite"), { recursive: true, force: true });
await writeFile(
  path.join(output, "build-info.json"),
  JSON.stringify(
    {
      hosting: "static",
      basePath: base,
      siteUrl: site,
      routes: routes.length,
      ai: false,
      pdf: "resume.pdf",
    },
    null,
    2,
  ) + "\n",
);
const main = await readFile(path.join(output, "index.html"), "utf8");
if (/\/api\/assistant|assistant-trigger|assistant-modal/.test(main))
  throw new Error("AI UI remains in static output");
console.log(
  JSON.stringify({
    staticBuild: true,
    output,
    basePath: base,
    siteUrl: site,
    routes: routes.length,
    pdfBytes: pdf.length,
  }),
);
