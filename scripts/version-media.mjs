import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const imageRoot = path.join(root, "apps/web/public/images");
const sourceFile = process.argv[2] ?? path.join(root, "packages/core/asset/screens.json");
const source = JSON.parse(await fs.readFile(sourceFile, "utf8"));
const generated = {};
for (const [slug, screens] of Object.entries(source)) {
  assert.match(slug, /^[a-z0-9-]+$/u);
  assert.ok(Array.isArray(screens) && screens.length > 0);
  assert.equal(new Set(screens.map((screen) => screen.id)).size, screens.length);
  generated[slug] = [];
  for (const screen of screens) {
    assert.match(screen.src, /^\/images\/[a-z0-9-]+\.webp$/u);
    assert.ok(screen.width > 0 && screen.height > 0);
    const filename = path.basename(screen.src);
    const bytes = await fs.readFile(path.join(imageRoot, filename));
    const digest = crypto.createHash("sha256").update(bytes).digest("hex").slice(0, 12);
    const versioned = `${filename.slice(0, -5)}.${digest}.webp`;
    await fs.writeFile(path.join(imageRoot, versioned), bytes);
    generated[slug].push({ ...screen, src: `/images/${versioned}` });
  }
}
const module = `// Generated by scripts/version-media.mjs. URLs change when image bytes change.\nimport type { ProjectScreen } from "@jeamxn/contract";\n\nexport const projectScreens: Record<string, ProjectScreen[]> = ${JSON.stringify(generated, null, 2)};\n`;
await fs.writeFile(path.join(root, "packages/core/src/screens.ts"), module);
console.log(
  JSON.stringify(
    {
      projects: Object.fromEntries(
        Object.entries(generated).map(([slug, screens]) => [slug, screens.length]),
      ),
      versioned: Object.values(generated)
        .flat()
        .map((screen) => screen.src),
    },
    null,
    2,
  ),
);
