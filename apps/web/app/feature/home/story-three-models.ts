type Materials = Record<keyof typeof PALETTE, MeshStandardMaterial>;
type Point = readonly [number, number, number];

function makeMaterials(): Materials {
  return Object.fromEntries(
    Object.entries(PALETTE).map(([name, color]) => [
      name,
      new MeshStandardMaterial({
        name: `story-${name}`,
        color,
        roughness: name === "gold" ? 0.48 : 0.72,
        metalness: name === "gold" ? 0.24 : 0.03,
      }),
    ]),
  ) as Materials;
}

function mesh(
  parent: Group,
  name: string,
  geometry: BufferGeometry,
  material: Material,
  position: Point = [0, 0, 0],
): Mesh {
  const result = new Mesh(geometry, material);
  result.name = name;
  result.position.set(...position);
  result.castShadow = true;
  result.receiveShadow = true;
  parent.add(result);
  return result;
}

function instances(
  parent: Group,
  name: string,
  geometry: BufferGeometry,
  material: Material,
  positions: readonly Point[],
): InstancedMesh {
  const result = new InstancedMesh(geometry, material, positions.length);
  result.name = name;
  result.castShadow = true;
  result.receiveShadow = true;
  const transform = new Matrix4();
  positions.forEach((position, index) => {
    result.setMatrixAt(index, transform.makeTranslation(...position));
  });
  result.instanceMatrix.needsUpdate = true;
  parent.add(result);
  return result;
}

function box(
  parent: Group,
  name: string,
  size: Point,
  material: Material,
  position: Point = [0, 0, 0],
  radius = 0.06,
): Mesh {
  return mesh(
    parent,
    name,
    new RoundedBoxGeometry(...size, 3, Math.min(radius, ...size.map((n) => n / 3))),
    material,
    position,
  );
}

function cylinder(
  parent: Group,
  name: string,
  radius: number,
  height: number,
  material: Material,
  position: Point,
): Mesh {
  return mesh(parent, name, new CylinderGeometry(radius, radius, height, 40), material, position);
}

function ring(
  parent: Group,
  name: string,
  radius: number,
  thickness: number,
  material: Material,
  position: Point,
): Mesh {
  return mesh(parent, name, new TorusGeometry(radius, thickness, 12, 48), material, position);
}

function sphere(
  parent: Group,
  name: string,
  radius: number,
  material: Material,
  position: Point,
): Mesh {
  return mesh(parent, name, new SphereGeometry(radius, 24, 16), material, position);
}

function tube(
  parent: Group,
  name: string,
  points: readonly Point[],
  radius: number,
  material: Material,
  curved = true,
): Mesh {
  const vertices = points.map((point) => new Vector3(...point));
  const path = curved ? new CatmullRomCurve3(vertices) : new CurvePath<Vector3>();
  if (path instanceof CurvePath) {
    for (let i = 1; i < vertices.length; i++) {
      path.add(new LineCurve3(vertices[i - 1], vertices[i]));
    }
  }
  return mesh(parent, name, new TubeGeometry(path, 48, radius, 12, false), material);
}

function extrude(shape: Shape, depth: number, bevel = 0.025): ExtrudeGeometry {
  const geometry = new ExtrudeGeometry(shape, {
    depth,
    steps: 1,
    curveSegments: 16,
    bevelEnabled: true,
    bevelSegments: 3,
    bevelSize: bevel,
    bevelThickness: bevel,
  });
  geometry.translate(0, 0, -depth / 2);
  return geometry;
}

/** Remove the coincident-axis triangles generated by a closed lathe profile. */
function lathe(profile: Vector2[], segments = 48): LatheGeometry {
  const geometry = new LatheGeometry(profile, segments);
  const index = geometry.getIndex();
  const position = geometry.getAttribute("position");
  if (index) {
    const indices: number[] = [];
    const a = new Vector3();
    const b = new Vector3();
    const c = new Vector3();
    for (let i = 0; i < index.count; i += 3) {
      a.fromBufferAttribute(position, index.getX(i));
      b.fromBufferAttribute(position, index.getX(i + 1));
      c.fromBufferAttribute(position, index.getX(i + 2));
      if (b.sub(a).cross(c.sub(a)).lengthSq() > 1e-18) {
        indices.push(index.getX(i), index.getX(i + 1), index.getX(i + 2));
      }
    }
    geometry.setIndex(indices);
  }
  geometry.normalizeNormals();
  return geometry;
}

