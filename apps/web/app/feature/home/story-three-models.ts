function normalizedModel(name: StoryTool, content: Group): Group {
  const root = new Group();
  root.name = name;
  root.userData = {
    kind: name,
    modeling: "manually-created-procedural-geometry",
    front: "+Z",
    up: "+Y",
  };
  content.name = `${name}-normalized-content`;
  root.add(content);
  root.updateMatrixWorld(true);
  const bounds = new Box3().setFromObject(root, true);
  const center = bounds.getCenter(new Vector3());
  const size = bounds.getSize(new Vector3());
  const scale = 2 / Math.max(size.x, size.y, size.z);
  content.scale.multiplyScalar(scale);
  content.position.copy(center).multiplyScalar(-scale);
  root.updateMatrixWorld(true);
  return root;
}

function disposeUnusedMaterials(models: Group[], materials: Materials): void {
  const used = new Set<Material>();
  for (const model of models) {
    model.traverse((object) => {
      if (object instanceof Mesh) {
        for (const material of Array.isArray(object.material)
          ? object.material
          : [object.material]) {
          used.add(material);
        }
      }
    });
  }
  for (const material of Object.values(materials)) {
    if (!used.has(material)) material.dispose();
  }
}

