export function createStoryModel(name: StoryTool): Group {
  const materials = makeMaterials();
  const root = normalizedModel(name, MODEL_FACTORIES[name](materials));
  disposeUnusedMaterials([root], materials);
  return root;
}

/**
 * Compatibility factory: music → laundry → calendar → document → chart → data →
 * chat → idea. Front +Z, up +Y, identity roots, centered AABBs with max size 2.
 * Dispose traversed geometries/materials with Sets to deduplicate shared resources.
 */
export function createStoryModels(): Group[] {
  const materials = makeMaterials();
  const models = (Object.keys(MODEL_FACTORIES) as StoryTool[]).map((name) =>
    normalizedModel(name, MODEL_FACTORIES[name](materials)),
  );
  disposeUnusedMaterials(models, materials);
  return models;
}
