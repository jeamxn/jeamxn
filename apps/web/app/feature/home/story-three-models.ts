function bubbleShape(width: number, height: number): Shape {
  const x = width / 2;
  const y = height / 2;
  const r = 0.2;
  const s = new Shape();
  s.moveTo(-x + r, -y);
  s.lineTo(-x + 0.12, -y - 0.26);
  s.lineTo(-x + 0.48, -y);
  s.lineTo(x - r, -y);
  s.quadraticCurveTo(x, -y, x, -y + r);
  s.lineTo(x, y - r);
  s.quadraticCurveTo(x, y, x - r, y);
  s.lineTo(-x + r, y);
  s.quadraticCurveTo(-x, y, -x, y - r);
  s.lineTo(-x, -y + r);
  s.quadraticCurveTo(-x, -y, -x + r, -y);
  s.closePath();
  return s;
}

